export function syntaxError(message: string, position?: number): PgError {
  return new PgError(SqlState.SYNTAX_ERROR, message, position !== undefined ? { position: position + 1 } : undefined);
}

export function notSupported(what: string): PgError {
  return new PgError(SqlState.FEATURE_NOT_SUPPORTED, `in-memory engine: ${what} is not supported`);
}

export function internalError(message: string): PgError {
  return new PgError(SqlState.INTERNAL_ERROR, message);
}
