/**
 * PostgreSQL-compatible error raised by the in-memory engine.
 *
 * Carries the same diagnostic fields the server sends in an ErrorResponse, so the driver
 * adapters can surface them exactly like `pg`'s `DatabaseError` / postgres.js' `PostgresError`.
 */
export interface PgErrorFields {
  detail?: string;
  hint?: string;
  position?: number;
  where?: string;
  schema?: string;
  table?: string;
  column?: string;
  dataType?: string;
  constraint?: string;
  routine?: string;
  internalQuery?: string;
  internalPosition?: number;
  noPosition?: boolean;
}

export class PgError extends Error {
  readonly code: string;
  readonly severity: string;
  detail?: string;
  hint?: string;
  position?: number;
  where?: string;
  schema?: string;
  table?: string;
  column?: string;
  dataType?: string;
  constraint?: string;
  routine?: string;
  internalQuery?: string;
  internalPosition?: number;
  /** reported without a query position even when raised while analyzing a positioned node */
  noPosition?: boolean;

  constructor(code: string, message: string, fields?: PgErrorFields, severity = 'ERROR') {
    super(message);
    this.name = 'PgError';
    this.code = code;
    this.severity = severity;
    if (fields) {
      Object.assign(this, fields);
    }
    Object.setPrototypeOf(this, PgError.prototype);
  }
}

